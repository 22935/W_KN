import { mkdir, readFile, writeFile, readdir, copyFile, access, unlink } from 'node:fs/promises';
import { join, resolve, basename } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { randomUUID } from 'node:crypto';
import matter from 'gray-matter';
import { validatePost, postMarkdown, slugify, versionHash } from './content.mjs';
import { syncRemotes } from './git-sync.mjs';

const exec=promisify(execFile);
export const postIdValid=id=>typeof id==='string'&&/^[\p{L}\p{N}][\p{L}\p{N}-]{0,99}$/u.test(id);
export async function listPublicPosts(root){
  const directory=join(root,'src/content/posts');await mkdir(directory,{recursive:true});
  const files=(await readdir(directory)).filter(f=>f.endsWith('.md'));
  return Promise.all(files.map(async file=>{const{data,content}=matter(await readFile(join(directory,file),'utf8'));return{id:basename(file,'.md'),...data,date:data.date instanceof Date?data.date.toISOString().slice(0,10):data.date,body:content};}));
}
export async function writePublicPost(root,input,id){
  const post=validatePost(input);if(!post.body.trim())throw new Error('正文不能为空');
  const postId=id||`${slugify(post.title)}-${randomUUID().slice(0,8)}`;
  if(!postIdValid(postId))throw new Error('文章 ID 无效');
  const postsRoot=join(root,'src/content/posts');await mkdir(postsRoot,{recursive:true});
  let body=post.body;
  // Absolute resource paths in Markdown must include the GitHub Pages base.
  // Import assets through the Markdown file using a path relative to this file;
  // Astro resolves them into deployment-safe build assets.
  body=body.replace(/!\[([^\]]*)\]\(\/?images\/imported\/([a-f0-9]{24}\.(?:png|jpg|gif|webp|avif))(\s+"[^"]*")?\)/g,(_all,alt,file,title)=>`![${alt}](../../assets/imported/${file}${title||''})`);
  const privateAssets=join(root,'.local/assets');const publicAssets=join(root,'src/assets/imported');
  const images=[...post.body.matchAll(/\/?images\/imported\/([a-f0-9]{24}\.(?:png|jpg|gif|webp|avif))/g)].map(m=>m[1]);
  if(images.length){await mkdir(publicAssets,{recursive:true});for(const file of new Set(images)){await copyFile(join(privateAssets,file),join(publicAssets,file)).catch(async error=>{try{await access(join(publicAssets,file));}catch{throw error;}});}}
  if(/^images\/imported\/[a-f0-9]{24}\.(png|jpg|gif|webp|avif)$/.test(post.cover)){const file=basename(post.cover);const dest=join(root,'public/images/imported');await mkdir(dest,{recursive:true});await copyFile(join(privateAssets,file),join(dest,file)).catch(async error=>{try{await access(join(dest,file));}catch{throw error;}});}
  if(id){const existing=join(postsRoot,`${id}.md`);try{await access(existing);}catch{throw new Error('原文章不存在，请以新文章保存');}}
  await writeFile(join(postsRoot,`${postId}.md`),postMarkdown({...post,body}));
  return{id:postId,hash:versionHash(post),file:`src/content/posts/${postId}.md`,status:'written-to-repository'};
}
export async function deletePublicPost(root,id){if(!postIdValid(id))throw new Error('文章 ID 无效');await unlink(join(root,'src/content/posts',`${id}.md`));}
export async function gitStatus(root){
  try{const {stdout}=await exec('git',['status','--short','--branch'],{cwd:root,timeout:10000});const remote=await exec('git',['remote','get-url','origin'],{cwd:root,timeout:10000}).catch(()=>({stdout:''}));return{ready:true,status:stdout,hasRemote:!!remote.stdout.trim()};}catch{return{ready:false,status:'当前目录尚未初始化 Git 仓库',hasRemote:false};}
}
export async function pushBlog(root){
  const state=await gitStatus(root);if(!state.ready||!state.hasRemote)throw new Error('请先初始化 Git 仓库并设置 origin，详见 README');
  // Only stage public content generated by the studio, never unrelated changes.
  const tracked=await exec('git',['diff','--cached','--name-only'],{cwd:root,timeout:10000});
  if(tracked.stdout.trim())throw new Error('暂存区已有改动，请先自行处理后再从工作台推送');
  const paths=['src/content/posts','src/assets/imported','public/images/imported','src/site.json'];const existing=[];
  for(const path of paths){try{await access(join(root,path));existing.push(path);}catch{}}
  await exec('git',['add','--',...existing],{cwd:root,timeout:10000});
  const diff=await exec('git',['diff','--cached','--name-only'],{cwd:root,timeout:10000});
  if(diff.stdout.trim())await exec('git',['commit','-m','content: publish journal updates'],{cwd:root,timeout:20000});
  return syncRemotes(root);
}
